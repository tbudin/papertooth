// Build: readable and minified CSS, an ES module, a browser script, and the filters as a static file.
import { build } from 'esbuild';
import { writeFileSync, mkdirSync, readFileSync, copyFileSync, rmSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import { filtersMarkup } from '../src/js/filters.js';
import { PICTURES, PAPER } from '../src/js/pictures.js';

mkdirSync('dist', { recursive: true });
const { version } = JSON.parse(readFileSync('package.json', 'utf8'));
// the source is published too, so VERSION is written in it rather than injected; keep the two in step
if (!readFileSync('src/js/index.js', 'utf8').includes(`VERSION = '${version}'`)) {
  throw new Error(`src/js/index.js VERSION does not match package.json (${version})`);
}
// MIT asks for the copyright line to travel with every copy, and the CDN files travel without LICENSE.
// "/*!" keeps the comment through a user's own minifier.
const notice = `/*! papertooth v${version} | (c) 2026 Thomas Budin | MIT License | github.com/tbudin/papertooth */`;
const banner = { css: notice, js: notice };

// picture stamps become CSS masks: ink where the drawing is, holes where it is cut out in the paper colour
// the mask's id is per picture: inlined into one page, several stamps must not share it
const pictureMask = ({ viewBox, body }, ink = '', id = 'pt') => {
  const [, , w, h] = viewBox.split(' ');
  const inner = body.replaceAll('currentColor', '#fff').replaceAll(PAPER, '#000');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}"><mask id="${id}" maskUnits="userSpaceOnUse" x="0" y="0" width="${w}" height="${h}">`
    + `<rect width="${w}" height="${h}"/>${inner}</mask><rect width="${w}" height="${h}"${ink} mask="url(#${id})"/></svg>`;
};
// SVG in a CSS url("…") only needs these escaped once its own quotes are single: a third of the size of encodeURIComponent
const svgURI = svg => svg.replace(/"/g, "'").replace(/[%#<>{}]/g, encodeURIComponent);
writeFileSync('src/css/pictures.css', '/* Generated by scripts/build.mjs from src/js/pictures.js: edit the drawings there. */\n'
  + Object.entries(PICTURES).map(([name, p]) => {
    const [, , w, h] = p.viewBox.split(' ');
    return `.pt-stamp[data-pic="${name}"] { --pt-pic: url("data:image/svg+xml,${svgURI(pictureMask(p))}"); --pt-pic-ratio: ${w} / ${h}; }`;
  }).join('\n') + '\n');

// papertooth/react takes the kit from the main entry ("papertooth"), so a page never runs two copies of it;
// the small pure helpers it draws with (seeded randomness, checkbox shapes) are bundled in
const useMainEntry = {
  name: 'use-main-entry',
  setup(b) { b.onResolve({ filter: /\/js\/index\.js$/ }, () => ({ path: 'papertooth', external: true })); }
};

rmSync('dist/chunks', { recursive: true, force: true });   // chunk names change with their content
const split = { bundle: true, format: 'esm', target: 'es2020', splitting: true, outdir: 'dist', banner, logLevel: 'warning', charset: 'ascii' };

await Promise.all([
  build({ entryPoints: ['src/css/index.css'], bundle: true, outfile: 'dist/papertooth.css', banner, logLevel: 'warning', charset: 'ascii' }),
  build({ entryPoints: ['src/css/index.css'], bundle: true, minify: true, outfile: 'dist/papertooth.min.css', banner, logLevel: 'warning', charset: 'ascii' }),
  // the same CSS inside @layer papertooth, for sites that order their CSS in cascade layers (Tailwind v4)
  build({ entryPoints: ['src/css/layer.css'], bundle: true, minify: true, outfile: 'dist/papertooth.layer.css', banner, logLevel: 'warning', charset: 'ascii' }),
  // the modules are split: diagrams and image effects are chunks the script fetches when a page has one, and
  // papertooth/diagram shares its chunk, so a page never loads that code twice
  build({ ...split, entryPoints: { papertooth: 'src/js/index.js', diagram: 'src/diagram/index.js' }, chunkNames: 'chunks/[name]-[hash]' }),
  build({ ...split, entryPoints: { 'papertooth.min': 'src/js/index.js', 'diagram.min': 'src/diagram/index.js' }, chunkNames: 'chunks/[name]-[hash].min', outExtension: { '.js': '.mjs' }, minify: true }),
  build({ entryPoints: ['src/js/auto.js'], bundle: true, format: 'iife', target: 'es2020', minify: true, outfile: 'dist/papertooth.min.js', banner, logLevel: 'warning', charset: 'ascii' }),
  // papertooth/shapes and papertooth/tokens: no DOM, for other renderers
  build({ entryPoints: ['src/shapes/index.js'], bundle: true, format: 'esm', target: 'es2020', outfile: 'dist/shapes.js', banner, logLevel: 'warning', charset: 'ascii' }),
  build({ entryPoints: ['src/tokens/index.js'], bundle: true, format: 'esm', target: 'es2020', outfile: 'dist/tokens.js', banner, logLevel: 'warning', charset: 'ascii' }),
  // "use client" lets Next.js server components import it; a directive may follow a comment but nothing else
  build({ entryPoints: ['src/react/index.js'], bundle: true, format: 'esm', target: 'es2020', external: ['react'], plugins: [useMainEntry],
    outfile: 'dist/react.js', banner: { js: notice + '\n"use client";' }, logLevel: 'warning', charset: 'ascii' })
]);
writeFileSync('dist/papertooth-filters.svg', filtersMarkup() + '\n');

// and as files of their own (papertooth/stamps/frog.svg, and stamps/ on the docs site): currentColor ink with real
// holes, so they work on any paper, inline or as an image
for (const dir of ['dist/stamps', 'docs/stamps']) {
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  for (const [name, p] of Object.entries(PICTURES)) {
    const [, , w, h] = p.viewBox.split(' ');
    const svg = pictureMask(p, ' fill="currentColor"', `pt-${name}`).replace('<svg ', `<svg width="${w}" height="${h}" role="img" aria-label="${p.label}" `);
    writeFileSync(`${dir}/${name}.svg`, svg + '\n');
  }
}

// one stylesheet per part, for pages that want only some of it (papertooth/css/base first, then any of these)
const CSS_PARTS = ['base', 'highlight', 'lines', 'marks', 'pictures', 'goods', 'planner', 'forms', 'extras', 'images', 'diagram'];
await Promise.all(CSS_PARTS.map(part => build({ entryPoints: [`src/css/${part}.css`], bundle: true, minify: true, outfile: `dist/css/${part}.css`, banner, logLevel: 'warning', charset: 'ascii' })));

// the docs page loads the built files from its own folder
for (const f of ['papertooth.min.css', 'papertooth.min.js']) copyFileSync('dist/' + f, 'docs/' + f);

const kb = n => (n / 1024).toFixed(1) + ' KB';
for (const f of ['papertooth.min.css', 'papertooth.min.js', 'papertooth.min.mjs', 'diagram.min.mjs', 'papertooth-filters.svg']) {
  const b = readFileSync('dist/' + f);
  console.log(f.padEnd(24), kb(b.length).padStart(9), ' gzip', kb(gzipSync(b).length).padStart(8));
}
